let currentLanguage = "en";

// UPDATE ALL TEXT AND PAGE DIRECTION WHEN THE LANGUAGE CHANGES
function applyLanguage(language) {
    currentLanguage = language;
    const isArabic = language === "ar";

    document.documentElement.lang = isArabic ? "ar" : "en";
    document.documentElement.dir = isArabic ? "rtl" : "ltr";
    document.body.classList.toggle("arabic", isArabic);

    document.querySelectorAll("[data-i18n]").forEach(function(element) {
        const key = element.getAttribute("data-i18n");
        if (translations[language][key] !== undefined) {
            element.textContent = translations[language][key];
        }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function(element) {
        const key = element.getAttribute("data-i18n-aria");
        if (translations[language][key] !== undefined) {
            element.setAttribute("aria-label", translations[language][key]);
        }
    });

    document.querySelectorAll("[data-i18n-title]").forEach(function(element) {
        const key = element.getAttribute("data-i18n-title");
        if (translations[language][key] !== undefined) {
            element.setAttribute("title", translations[language][key]);
        }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach(function(element) {
        const key = element.getAttribute("data-i18n-alt");
        if (translations[language][key] !== undefined) {
            element.setAttribute("alt", translations[language][key]);
        }
    });

    const languageText = document.getElementById("languageText");
    languageText.textContent = translations[language].language;

    // Arabic starts with the sidebar on the right. English starts on the left.
    if (isArabic) {
        pageLayout.classList.add("sidebar-right");
        moveSidebarBtn.setAttribute("aria-pressed", "true");
    } else {
        pageLayout.classList.remove("sidebar-right");
        moveSidebarBtn.setAttribute("aria-pressed", "false");
    }

    updateMoveSidebarText();
    updatePageTitle();
    updateHeartButton();
}

// SIDEBAR NAVIGATION: CHANGE THE ACTIVE ITEM AND PAGE HEADING
const navLinks = document.querySelectorAll(".nav-link");
const pageTitle = document.getElementById("pageTitle");

function updatePageTitle() {
    const activeLink = document.querySelector(".nav-link.active");
    const selectedPage = activeLink.getAttribute("data-page");

    if (selectedPage === "Dashboard") {
        pageTitle.textContent = translations[currentLanguage].mainTitle;
        return;
    }

    const pageTranslationKeys = {
        "Web Design": "webDesign",
        "UI Layers": "uiLayers",
        "AI Courses": "aiCourses",
        "Components": "components",
        "Templates": "templates",
        "Widgets": "widgets",
        "Projects": "projects",
        "Live Preview": "livePreview",
        "Responsive Design": "responsiveDesign",
        "Code Preview": "codePreview",
        "Typography": "typography",
        "Animation": "animation",
        "Plugins": "plugins",
        "Settings": "settings"
    };

    pageTitle.textContent = translations[currentLanguage][pageTranslationKeys[selectedPage]];
}

navLinks.forEach(function(link) {
    link.addEventListener("click", function(event) {
        event.preventDefault();

        navLinks.forEach(function(item) {
            item.classList.remove("active");
        });

        link.classList.add("active");
        updatePageTitle();
    });
});

// MOVE THE SIDEBAR FROM ONE SIDE TO THE OTHER
const pageLayout = document.getElementById("pageLayout");
const moveSidebarBtn = document.getElementById("moveSidebarBtn");
const moveSidebarText = document.getElementById("moveSidebarText");

function updateMoveSidebarText() {
    const sidebarIsRight = pageLayout.classList.contains("sidebar-right");
    const key = sidebarIsRight ? "moveSidebarLeft" : "moveSidebarRight";
    moveSidebarText.textContent = translations[currentLanguage][key];
}

moveSidebarBtn.addEventListener("click", function() {
    pageLayout.classList.toggle("sidebar-right");
    const sidebarIsRight = pageLayout.classList.contains("sidebar-right");
    moveSidebarBtn.setAttribute("aria-pressed", sidebarIsRight);
    updateMoveSidebarText();
});

// RESIZE THE SIDEBAR BY DRAGGING THE VERTICAL DIVIDER
const resizeHandle = document.getElementById("resizeHandle");
const minimumSidebarWidth = 150;
const maximumSidebarWidth = 340;
const startingSidebarWidth = 220;

function setSidebarWidth(newWidth) {
    const safeWidth = Math.max(
        minimumSidebarWidth,
        Math.min(maximumSidebarWidth, newWidth)
    );

    pageLayout.style.setProperty("--sidebar-width", safeWidth + "px");
    resizeHandle.setAttribute("aria-valuenow", Math.round(safeWidth));
}

resizeHandle.addEventListener("pointerdown", function(event) {
    if (window.innerWidth <= 950) {
        return;
    }

    event.preventDefault();
    pageLayout.classList.add("is-resizing");
    resizeHandle.setPointerCapture(event.pointerId);
});

resizeHandle.addEventListener("pointermove", function(event) {
    if (!pageLayout.classList.contains("is-resizing")) {
        return;
    }

    const layoutBounds = pageLayout.getBoundingClientRect();
    let newWidth;

    if (pageLayout.classList.contains("sidebar-right")) {
        newWidth = layoutBounds.right - event.clientX;
    } else {
        newWidth = event.clientX - layoutBounds.left;
    }

    setSidebarWidth(newWidth);
});

function stopResizing() {
    pageLayout.classList.remove("is-resizing");
}

resizeHandle.addEventListener("pointerup", stopResizing);
resizeHandle.addEventListener("pointercancel", stopResizing);

resizeHandle.addEventListener("keydown", function(event) {
    const sidebarIsRight = pageLayout.classList.contains("sidebar-right");
    const change = 10;
    const currentWidth = parseInt(
        getComputedStyle(pageLayout).getPropertyValue("--sidebar-width"), 10
    );

    if (event.key === "ArrowRight") {
        event.preventDefault();
        setSidebarWidth(currentWidth + (sidebarIsRight ? -change : change));
    }

    if (event.key === "ArrowLeft") {
        event.preventDefault();
        setSidebarWidth(currentWidth + (sidebarIsRight ? change : -change));
    }
});

resizeHandle.addEventListener("dblclick", function() {
    setSidebarWidth(startingSidebarWidth);
});

// SWITCH BETWEEN THE 360-DEGREE HEART SCAN AND THE INTERACTIVE 3D MODEL
const heartMedia = document.getElementById("heartMedia");
const heartViewButton = document.getElementById("heartViewButton");
const heartHint = document.getElementById("heartHint");
let interactiveHeartIsOpen = false;

function updateHeartButton() {
    if (interactiveHeartIsOpen) {
        heartViewButton.innerHTML = '<i class="fa-solid fa-rotate-left"></i><span>' +
            translations[currentLanguage].backTo360 + '</span>';
        heartHint.textContent = translations[currentLanguage].heartExploreHint;
    } else {
        heartViewButton.innerHTML = '<i class="fa-solid fa-cube"></i><span>' +
            translations[currentLanguage].explore3d + '</span>';
        heartHint.textContent = translations[currentLanguage].heartBackHint;
    }
}

heartViewButton.addEventListener("click", function() {
    if (interactiveHeartIsOpen) {
        heartMedia.innerHTML = `
            <img
                class="heart-gif"
                src="https://upload.wikimedia.org/wikipedia/commons/e/ec/Real_Human_Heart_Turntable.gif"
                alt="${translations[currentLanguage].heartAlt}"
                title="${translations[currentLanguage].heartTitle}"
            >
        `;
        interactiveHeartIsOpen = false;
    } else {
        heartMedia.innerHTML = `
            <iframe
                class="heart-3d-frame"
                title="${currentLanguage === "ar" ? "نموذج ثلاثي الأبعاد لقلب بشري حقيقي" : "Interactive 3D model of a real human heart"}"
                src="https://sketchfab.com/models/9551a60cb37c4bfa8d56dfd2f1ac34e5/embed?autostart=1&autospin=0.15&ui_theme=light&ui_infos=0&ui_controls=1&ui_hint=0"
                allow="autoplay; fullscreen; xr-spatial-tracking"
                allowfullscreen
                loading="lazy">
            </iframe>
        `;
        interactiveHeartIsOpen = true;
    }

    updateHeartButton();
});

